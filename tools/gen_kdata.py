"""Writes Erdos112/KData.lean and Erdos112/KCheck/*.lean from tools/j_tables.txt.

j_tables.txt is the list of the 24 graphs on J found by step 1 of the search (printed by Lean,
see README_KERNEL.md). Nothing here is trusted: the theorem `covered_Js` (KCover.lean) checks in
the kernel that the list is complete, and each KCheck theorem is checked in the kernel.
Run from the lean_kernel folder: python3 tools/gen_kdata.py
"""
import ast, os
js = ast.literal_eval(open('tools/j_tables.txt').read())
assert len(js) == 24
out = ['module', '', 'public import Erdos112.KSearch', '', '@[expose] public section', '',
       '/-!', '# The 24 graphs on `J` found by step 1 of the search (data, generated)', '',
       'Row `j` of a table gives the masks (out, in, non-adjacent) of `J j` over `J 0, ..., J (j-1)`.',
       'That the list is complete is the kernel-checked theorem `covered_Js` in `KCover.lean`.',
       'Generated by `tools/gen_kdata.py`.', '-/', '', 'namespace Erdos112.K', '']
for k, t in enumerate(js):
    rows = ', '.join('⟨%d, %d, %d⟩' % r for r in t)
    out.append('def J%02d : List Row := [%s]' % (k, rows))
out += ['', 'def Js : List (List Row) :=', '  [' + ', '.join('J%02d' % k for k in range(24)) + ']', '',
        'end Erdos112.K', '']
open('Erdos112/KData.lean', 'w').write('\n'.join(out))
for d, tag, name in ((True, 'A', '32'), (False, 'B', '23')):
    for f in range(6):
        o = ['module', '', 'public import Erdos112.KData', '', '@[expose] public section', '',
             '/-! Step 2 of the search, type (%s,%s), on four of the 24 graphs on `J`.' % (name[0], name[1]),
             'Each theorem is one kernel computation (`decide +kernel`). Generated by `tools/gen_kdata.py`. -/',
             '', 'namespace Erdos112.K', '']
        for k in range(4 * f, 4 * f + 4):
            o.append('theorem s%s_%02d : stage2 %s J%02d = false := by decide +kernel' % (name, k, 'true' if d else 'false', k))
        o += ['', 'end Erdos112.K', '']
        open('Erdos112/KCheck/%s%d.lean' % (tag, f), 'w').write('\n'.join(o))

o = ['module', ''] + ['public import Erdos112.KCheck.' + t + str(f) for t in 'AB' for f in range(6)]
o += ['', '@[expose] public section', '', '/-! Step 2 of the search fails on every one of the 24 graphs on `J`, for both types.',
      'Collects the 48 kernel-checked theorems of `KCheck/A*.lean` and `KCheck/B*.lean`.',
      'Generated by `tools/gen_kdata.py`. -/', '', 'namespace Erdos112.K', '']
for name, d in (('32', 'true'), ('23', 'false')):
    o.append('theorem all%s : ∀ J ∈ Js, stage2 %s J = false := by' % (name, d))
    o.append('  intro J hJ')
    o.append('  simp only [Js, List.mem_cons, List.not_mem_nil, or_false] at hJ')
    o.append('  rcases hJ with ' + ' | '.join(['rfl'] * 24))
    for k in range(24):
        o.append('  · exact s%s_%02d' % (name, k))
    o.append('')
o += ['end Erdos112.K', '']
open('Erdos112/KCheck/All.lean', 'w').write('\n'.join(o))
